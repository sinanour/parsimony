import { X509Certificate, createPrivateKey } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

// ---------- .env ----------

/** Parses KEY=VALUE lines (comments and blank lines ignored; surrounding quotes stripped). */
export function parseEnv(text: string): Map<string, string> {
  const env = new Map<string, string>();
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const m = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (!m) continue;
    let v = m[2];
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1);
    env.set(m[1], v);
  }
  return env;
}

export interface ValidatedConfig {
  env: Map<string, string>;
  errors: string[];
  warnings: string[];
  httpsEnabled: boolean;
  httpPort: number;
  httpsPort: number;
}

const isBool = (v: string) => v === 'true' || v === 'false';
const isPort = (v: string) => /^\d+$/.test(v) && Number(v) >= 1 && Number(v) <= 65535;

/** Checks the deployment .env before anything is uploaded. */
export function validateConfig(env: Map<string, string>): ValidatedConfig {
  const errors: string[] = [];
  const warnings: string[] = [];
  const get = (k: string) => env.get(k)?.trim() ?? '';

  for (const k of ['HTTP_PORT', 'HTTPS_PORT']) if (get(k) && !isPort(get(k))) errors.push(`${k} must be a port number (1–65535)`);
  for (const k of ['ENABLE_HTTPS', 'HTTPS_REDIRECT', 'SMTP_SECURE']) if (get(k) && !isBool(get(k))) errors.push(`${k} must be true or false`);
  if (get('HTTP_PORT') && get('HTTP_PORT') === get('HTTPS_PORT')) errors.push('HTTP_PORT and HTTPS_PORT must differ');
  if (get('DATA_VOLUME_PATH') && !get('DATA_VOLUME_PATH').startsWith('/')) errors.push('DATA_VOLUME_PATH must be an absolute path on the target host');
  if (get('JWT_SECRET') && get('JWT_SECRET').length < 32) errors.push('JWT_SECRET must be at least 32 characters (or leave it unset to generate one)');
  if (get('ADMIN_EMAIL') && !get('ADMIN_PASSWORD')) errors.push('ADMIN_PASSWORD is required when ADMIN_EMAIL is set');
  if (get('ADMIN_PASSWORD') && get('ADMIN_PASSWORD').length < 8) errors.push('ADMIN_PASSWORD must be at least 8 characters');
  if (/change[-_ ]?me|change[-_ ]this/i.test(get('ADMIN_PASSWORD'))) errors.push('ADMIN_PASSWORD still has the placeholder value');
  if (get('PUBLIC_URL') && !/^https?:\/\/[^/\s]+/.test(get('PUBLIC_URL'))) errors.push('PUBLIC_URL must look like https://parsimony.example.com');
  if (get('SMTP_HOST') && !get('PUBLIC_URL')) warnings.push('SMTP_HOST is set but PUBLIC_URL is not, so password reset by email stays off');
  for (const [k, v] of env) if (/\s#/.test(v)) warnings.push(`${k} contains " #"; inline comments are not supported in .env and become part of the value`);

  const httpsEnabled = get('ENABLE_HTTPS') === 'true';
  if (!httpsEnabled) warnings.push('ENABLE_HTTPS is false: passwords and data will cross the network unencrypted unless another proxy terminates TLS');
  return { env, errors, warnings, httpsEnabled, httpPort: Number(get('HTTP_PORT') || 80), httpsPort: Number(get('HTTPS_PORT') || 443) };
}

/** The .env written to the host: the user's settings plus the release's image tag. */
export function renderEnv(env: Map<string, string>, imageTag: string): string {
  const out = new Map(env);
  out.set('COMPOSE_PROJECT_NAME', 'parsimony');
  out.set('IMAGE_TAG', imageTag);
  return [`# Generated by the Parsimony deploy CLI for release ${imageTag}`, ...[...out].map(([k, v]) => `${k}=${v}`)].join('\n') + '\n';
}

// ---------- certificates ----------

const PAIRS: [string, string][] = [
  ['fullchain.pem', 'privkey.pem'],
  ['fullchain1.pem', 'privkey1.pem'],
  ['server.crt', 'server.key'],
  ['cert.pem', 'key.pem'],
];

export interface CertCheck {
  certificate: string;
  key: string;
  subject: string;
  validTo: Date;
  daysLeft: number;
}

function walk(dir: string): string[] {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : e.isFile() || e.isSymbolicLink() ? [p] : [];
  });
}

/** Finds the pair nginx will use (same search order as configure-parsimony.sh) and checks it. */
export function checkCertificates(dir: string, now = new Date()): CertCheck {
  const files = walk(dir).sort();
  for (const [certName, keyName] of PAIRS) {
    for (const cert of files.filter((f) => path.basename(f) === certName)) {
      const key = path.join(path.dirname(cert), keyName);
      if (!fs.existsSync(key)) continue;
      let x509: X509Certificate;
      try {
        x509 = new X509Certificate(fs.readFileSync(cert));
      } catch (e) {
        throw new Error(`${cert} is not a valid PEM certificate (${e instanceof Error ? e.message : e})`);
      }
      let matches: boolean;
      try {
        matches = x509.checkPrivateKey(createPrivateKey(fs.readFileSync(key)));
      } catch (e) {
        throw new Error(`${key} is not a valid, unencrypted private key (${e instanceof Error ? e.message : e})`);
      }
      if (!matches) throw new Error(`${key} does not belong to ${cert}`);
      const validTo = new Date(x509.validTo);
      const daysLeft = Math.floor((validTo.getTime() - now.getTime()) / 86_400_000);
      if (daysLeft < 0) throw new Error(`${cert} expired on ${validTo.toISOString().slice(0, 10)}`);
      return { certificate: cert, key, subject: x509.subject.replace(/\n/g, ', '), validTo, daysLeft };
    }
  }
  throw new Error(`No certificate/key pair in ${dir}. Expected one of: ${PAIRS.map((p) => p.join(' + ')).join(', ')}.`);
}

// ---------- compose ----------

/** Removes `build:` sections so the host only ever runs the transferred, versioned images. */
export function stripBuildSections(compose: string): string {
  const lines = compose.split('\n');
  const out: string[] = [];
  for (let i = 0; i < lines.length; i++) {
    const m = /^(\s*)build:\s*$/.exec(lines[i]);
    if (!m) {
      out.push(lines[i]);
      continue;
    }
    const indent = m[1].length;
    while (i + 1 < lines.length && (lines[i + 1].trim() === '' || lines[i + 1].search(/\S/) > indent)) i++;
  }
  return out.join('\n');
}

// ---------- release history (kept on the host in <dir>/state.json) ----------

export interface ReleaseState {
  current: string | null;
  /** Newest first; includes current. */
  releases: string[];
  history: { at: string; event: 'deploy' | 'rollback' | 'failed'; version: string; by?: string }[];
}

export const emptyState = (): ReleaseState => ({ current: null, releases: [], history: [] });

export function parseState(text: string): ReleaseState {
  try {
    const s = JSON.parse(text) as Partial<ReleaseState>;
    return { current: s.current ?? null, releases: Array.isArray(s.releases) ? s.releases : [], history: Array.isArray(s.history) ? s.history : [] };
  } catch {
    return emptyState();
  }
}

/** The release before the current one. */
export function previousRelease(s: ReleaseState): string | null {
  const i = s.current ? s.releases.indexOf(s.current) : -1;
  return i >= 0 ? (s.releases[i + 1] ?? null) : (s.releases[0] ?? null);
}

export function recordDeploy(s: ReleaseState, version: string, keep: number, by?: string): { state: ReleaseState; pruned: string[] } {
  const releases = [version, ...s.releases.filter((r) => r !== version)];
  return {
    state: { current: version, releases: releases.slice(0, keep), history: [...s.history, { at: new Date().toISOString(), event: 'deploy' as const, version, by }].slice(-100) },
    pruned: releases.slice(keep),
  };
}

export function recordRollback(s: ReleaseState, to: string, by?: string): ReleaseState {
  // The release rolled back from is dropped so a second rollback goes further back, not forward.
  const releases = s.releases.filter((r) => r !== s.current);
  return { current: to, releases, history: [...s.history, { at: new Date().toISOString(), event: 'rollback' as const, version: to, by }].slice(-100) };
}

export function recordFailure(s: ReleaseState, version: string, by?: string): ReleaseState {
  return { ...s, history: [...s.history, { at: new Date().toISOString(), event: 'failed' as const, version, by }].slice(-100) };
}

/** e.g. 20261122-153000-ab12cd3 */
export function versionTag(now = new Date(), gitSha?: string | null): string {
  const p = (n: number) => String(n).padStart(2, '0');
  const stamp = `${now.getUTCFullYear()}${p(now.getUTCMonth() + 1)}${p(now.getUTCDate())}-${p(now.getUTCHours())}${p(now.getUTCMinutes())}${p(now.getUTCSeconds())}`;
  return gitSha ? `${stamp}-${gitSha.slice(0, 7)}` : stamp;
}
